#!/usr/bin/env python3
"""
Generatore di App Clip Code rotondi ufficiali Apple per le stazioni di In Orario.
Usa il tool ufficiale Apple `AppClipCodeGenerator` (/usr/local/bin/AppClipCodeGenerator).

Uso:
  python3 genera_appclip_stazioni.py --serve                 # Avvia l'interfaccia web locale (http://localhost:8765)
  python3 genera_appclip_stazioni.py --code S01700           # Genera SVG per singola stazione
  python3 genera_appclip_stazioni.py --presets               # Genera SVG per le 10 stazioni preset + appclip_presets.js
"""

import argparse
import base64
import json
import os
import shutil
import subprocess
import tempfile
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlparse

TOOLS_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = TOOLS_DIR.parent
STATIONS_JSON = PROJECT_ROOT / "InOrarioClip" / "rfi_stations.json"
OUTPUT_DIR = TOOLS_DIR / "appclip_codes"
PRESETS_JS = TOOLS_DIR / "appclip_presets.js"

BASE_URL = "https://inorario.toreroclub.com"

PRESET_STATIONS = [
    {"name": "Milano Centrale", "code": "S01700"},
    {"name": "Milano Porta Garibaldi", "code": "S01645"},
    {"name": "Milano P.ta Garibaldi (Passante)", "code": "S01647"},
    {"name": "Milano Repubblica", "code": "S01648"},
    {"name": "Milano Rogoredo", "code": "S01701"},
    {"name": "Milano Lambrate", "code": "S01643"},
    {"name": "Magenta", "code": "S01040"},
    {"name": "Torino Lingotto", "code": "S00452"},
    {"name": "Roma Termini", "code": "S08409"},
    {"name": "Bologna Centrale", "code": "S05043"},
]


def find_generator_bin() -> str:
    found = shutil.which("AppClipCodeGenerator")
    if found:
        return found
    fallback = "/usr/local/bin/AppClipCodeGenerator"
    if os.path.exists(fallback):
        return fallback
    raise FileNotFoundError(
        "AppClipCodeGenerator non trovato. Installalo da Apple Developer Downloads."
    )


def generate_appclip_svg(
    code: str,
    fg: str = "000000",
    bg: str = "FF9F0A",
    code_type: str = "cam",
    logo: str = "none",
    index: str | None = None,
) -> bytes:
    generator = find_generator_bin()
    clean_code = code.strip().upper()
    if not clean_code:
        raise ValueError("Codice stazione vuoto")

    # Nota: /s/<code > supera il limite byte dell'App Clip Code visivo Apple;
    # https://inorario.toreroclub.com/<vtID> è supportato direttamente da ClipLinkHandler.swift.
    target_url = f"{BASE_URL}/{clean_code}"

    with tempfile.NamedTemporaryFile(suffix=".svg", delete=False) as tmp:
        tmp_path = tmp.name

    try:
        cmd = [generator, "generate", "--url", target_url, "--type", code_type, "--logo", logo, "--output", tmp_path]
        if index is not None and index != "":
            cmd.extend(["--index", str(index)])
        else:
            cmd.extend(["--foreground", fg.lstrip("#"), "--background", bg.lstrip("#")])

        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            err = (res.stderr or res.stdout or "Errore sconosciuto").strip()
            raise RuntimeError(err)

        with open(tmp_path, "rb") as f:
            return f.read()
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)


def load_all_stations() -> list[dict]:
    if not STATIONS_JSON.exists():
        return []
    with open(STATIONS_JSON, "r", encoding="utf-8") as f:
        data = json.load(f)
    return [
        {"name": item.get("name", ""), "code": item.get("vtID", ""), "rfiID": item.get("id", "")}
        for item in data
        if item.get("vtID")
    ]


def build_presets() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    presets_map = {}

    for st in PRESET_STATIONS:
        code = st["code"]
        svg_bytes = generate_appclip_svg(code, fg="000000", bg="FF9F0A", logo="none")
        out_file = OUTPUT_DIR / f"{code}.svg"
        out_file.write_bytes(svg_bytes)
        presets_map[code] = "data:image/svg+xml;base64," + base64.b64encode(svg_bytes).decode("ascii")
        print(f"Generato {out_file} ({st['name']})")

    js_content = "// Auto-generated by genera_appclip_stazioni.py\n"
    js_content += f"const APPCLIP_PRESETS = {json.dumps(presets_map, indent=2)};\n"
    PRESETS_JS.write_text(js_content, encoding="utf-8")
    print(f"Aggiornato {PRESETS_JS}")


class AppClipHandler(SimpleHTTPRequestHandler):
    ALL_STATIONS = load_all_stations()

    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(TOOLS_DIR), **kwargs)

    def do_GET(self):
        parsed = urlparse(self.path)

        if parsed.path == "/":
            self.path = "/genera_qr_stazioni.html"
            return super().do_GET()

        if parsed.path == "/api/appclip":
            qs = parse_qs(parsed.query)
            code = qs.get("code", ["S01700"])[0]
            fg = qs.get("fg", ["000000"])[0]
            bg = qs.get("bg", ["FF9F0A"])[0]
            code_type = qs.get("type", ["cam"])[0]
            logo = qs.get("logo", ["none"])[0]
            index = qs.get("index", [None])[0]
            try:
                svg_bytes = generate_appclip_svg(
                    code=code, fg=fg, bg=bg, code_type=code_type, logo=logo, index=index
                )
                self.send_response(200)
                self.send_header("Content-Type", "image/svg+xml; charset=utf-8")
                self.send_header("Cache-Control", "no-store")
                self.end_headers()
                self.wfile.write(svg_bytes)
            except Exception as e:
                self.send_response(400)
                self.send_header("Content-Type", "application/json; charset=utf-8")
                self.end_headers()
                self.wfile.write(json.dumps({"error": str(e)}).encode("utf-8"))
            return

        if parsed.path == "/api/stations":
            qs = parse_qs(parsed.query)
            q = qs.get("q", [""])[0].strip().lower()
            if not q:
                results = self.ALL_STATIONS[:30]
            else:
                results = [
                    s for s in self.ALL_STATIONS
                    if q in s["name"].lower() or q in s["code"].lower()
                ][:30]
            self.send_response(200)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.end_headers()
            self.wfile.write(json.dumps(results).encode("utf-8"))
            return

        return super().do_GET()


def main():
    parser = argparse.ArgumentParser(description="Generatore App Clip Code In Orario")
    parser.add_argument("--serve", action="store_true", help="Avvia server web locale su http://localhost:8765")
    parser.add_argument("--port", type=int, default=8765, help="Porta del server web locale")
    parser.add_argument("--presets", action="store_true", help="Rigenera gli SVG preset e appclip_presets.js")
    parser.add_argument("--code", type=str, help="Codice stazione vtID (es. S01700)")
    parser.add_argument("--fg", type=str, default="000000", help="Colore foreground hex (default 000000)")
    parser.add_argument("--bg", type=str, default="FF9F0A", help="Colore background hex (default FF9F0A)")
    parser.add_argument("--logo", type=str, default="none", choices=["none", "badge"], help="Includi badge Apple")
    parser.add_argument("--type", type=str, default="cam", choices=["cam", "nfc"], help="Tipo codice (cam/nfc)")
    args = parser.parse_args()

    if args.presets:
        build_presets()
        return

    if args.code:
        OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
        svg_bytes = generate_appclip_svg(
            code=args.code, fg=args.fg, bg=args.bg, code_type=args.type, logo=args.logo
        )
        out_path = OUTPUT_DIR / f"{args.code.strip().upper()}.svg"
        out_path.write_bytes(svg_bytes)
        print(f"Generato: {out_path}")
        return

    # Default: serve
    server = ThreadingHTTPServer(("127.0.0.1", args.port), AppClipHandler)
    print(f"Server App Clip Code avviato su http://localhost:{args.port}")
    print("Premi Ctrl+C per fermare.")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nServer fermato.")


if __name__ == "__main__":
    main()
